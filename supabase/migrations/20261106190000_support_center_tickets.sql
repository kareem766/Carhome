-- Phase 3: secure support tickets and threaded replies.
create table if not exists public.support_tickets (
  id uuid primary key default gen_random_uuid(),
  ticket_number bigint generated by default as identity unique not null,
  user_id uuid not null references auth.users(id) on delete cascade,
  subject text not null check (char_length(btrim(subject)) between 5 and 160),
  category text not null default 'general'
    check (category in ('general','account','payment','vehicle','requests','technical','suggestion','other')),
  priority text not null default 'normal'
    check (priority in ('low','normal','high')),
  status text not null default 'open'
    check (status in ('open','in_progress','waiting_user','resolved','closed')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  last_message_at timestamptz not null default now()
);

create table if not exists public.support_ticket_messages (
  id uuid primary key default gen_random_uuid(),
  ticket_id uuid not null references public.support_tickets(id) on delete cascade,
  sender_user_id uuid not null references auth.users(id) on delete cascade,
  body text not null check (char_length(btrim(body)) between 1 and 4000),
  created_at timestamptz not null default now()
);

create index if not exists support_tickets_user_updated_idx
  on public.support_tickets(user_id, updated_at desc);
create index if not exists support_tickets_status_updated_idx
  on public.support_tickets(status, updated_at desc);
create index if not exists support_ticket_messages_ticket_created_idx
  on public.support_ticket_messages(ticket_id, created_at asc);

create or replace function public.support_is_platform_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.platform_admins
    where user_id = (select auth.uid())
  );
$$;
revoke all on function public.support_is_platform_admin() from public, anon;
grant execute on function public.support_is_platform_admin() to authenticated;

alter table public.support_tickets enable row level security;
alter table public.support_ticket_messages enable row level security;

drop policy if exists "support tickets visible to owner or platform admin" on public.support_tickets;
create policy "support tickets visible to owner or platform admin"
on public.support_tickets for select to authenticated
using (user_id = (select auth.uid()) or public.support_is_platform_admin());

drop policy if exists "users create their own support tickets" on public.support_tickets;
create policy "users create their own support tickets"
on public.support_tickets for insert to authenticated
with check (user_id = (select auth.uid()));

drop policy if exists "only platform admins update support tickets" on public.support_tickets;
create policy "only platform admins update support tickets"
on public.support_tickets for update to authenticated
using (public.support_is_platform_admin())
with check (public.support_is_platform_admin());

drop policy if exists "support messages visible to ticket owner or platform admin" on public.support_ticket_messages;
create policy "support messages visible to ticket owner or platform admin"
on public.support_ticket_messages for select to authenticated
using (
  exists (
    select 1 from public.support_tickets t
    where t.id = ticket_id
      and (t.user_id = (select auth.uid()) or public.support_is_platform_admin())
  )
);

drop policy if exists "ticket participants can send support messages" on public.support_ticket_messages;
create policy "ticket participants can send support messages"
on public.support_ticket_messages for insert to authenticated
with check (
  sender_user_id = (select auth.uid())
  and exists (
    select 1 from public.support_tickets t
    where t.id = ticket_id
      and (
        public.support_is_platform_admin()
        or (t.user_id = (select auth.uid()) and t.status not in ('resolved','closed'))
      )
  )
);

grant select, insert, update on public.support_tickets to authenticated;
grant select, insert on public.support_ticket_messages to authenticated;

create or replace function public.support_touch_ticket_on_message()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  update public.support_tickets
     set updated_at = now(), last_message_at = now(),
         status = case
           when status = 'waiting_user' and exists (
             select 1 from public.platform_admins where user_id = new.sender_user_id
           ) then 'in_progress'
           when status = 'waiting_user' then status
           when status = 'resolved' and not exists (
             select 1 from public.platform_admins where user_id = new.sender_user_id
           ) then 'open'
           else status
         end
   where id = new.ticket_id;
  return new;
end;
$$;
revoke all on function public.support_touch_ticket_on_message() from public, anon, authenticated;

drop trigger if exists support_touch_ticket_after_message on public.support_ticket_messages;
create trigger support_touch_ticket_after_message
after insert on public.support_ticket_messages
for each row execute function public.support_touch_ticket_on_message();
